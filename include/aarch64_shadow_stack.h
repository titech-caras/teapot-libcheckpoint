/* Shared with Python instrumentation. Use decimal literals without leading zeroes. */
#define AARCH64_SHADOW_STACK_SIZE 8388608
#define AARCH64_SHADOW_STACK_DIFT_OFFSET 0
#define AARCH64_SHADOW_STACK_MEMLOG_OFFSET 64
#define AARCH64_SHADOW_STACK_ASAN_OFFSET 128
#define AARCH64_SHADOW_STACK_GADGET_MEM_OFFSET 192
#define AARCH64_SHADOW_STACK_GADGET_PORT_OFFSET 240
#define AARCH64_SHADOW_STACK_COVERAGE_OFFSET 288
#define AARCH64_SHADOW_STACK_CONTROL_OFFSET 320
#define AARCH64_SHADOW_STACK_RESTORE_OFFSET 352
#define AARCH64_SHADOW_STACK_INDIRECT_TARGET_OFFSET 384
#define AARCH64_SHADOW_STACK_REPORT_OFFSET 416
#define AARCH64_SHADOW_STACK_ABI_OFFSET 448
