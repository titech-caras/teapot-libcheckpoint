#define AARCH64_SHADOW_STACK_TEXT_DIFT_LLVM_OFFSET 512

#if AARCH64_SHADOW_STACK_SIZE < 4096 || AARCH64_SHADOW_STACK_SIZE % 4096 != 0 || \
    (AARCH64_SHADOW_STACK_SIZE >> 12) > 4095
#error "AArch64 shadow stack size must be 1-4095 pages for one add/sub immediate"
#endif

#if AARCH64_SHADOW_STACK_CONTROL_OFFSET < 0 || AARCH64_SHADOW_STACK_CONTROL_OFFSET > 504 || \
    AARCH64_SHADOW_STACK_CONTROL_OFFSET % 8 != 0 || \
    AARCH64_SHADOW_STACK_REPORT_OFFSET < 0 || AARCH64_SHADOW_STACK_REPORT_OFFSET > 504 || \
    AARCH64_SHADOW_STACK_REPORT_OFFSET % 8 != 0
#error "AArch64 control/report shadow stack offsets must fit a register-pair immediate"
#endif
